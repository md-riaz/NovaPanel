type siteWordPressArgs struct {
	Title         string `json:"title"`
	AdminUsername string `json:"admin_username"`
	AdminEmail    string `json:"admin_email"`
}

type siteCreateArgs struct {
	Name          string             `json:"name,omitempty"`
	Type          string             `json:"type"`
	PrimaryDomain string             `json:"primary_domain"`
	PHPVersion    *string            `json:"php_version,omitempty"`
	SiteID        string             `json:"site_id,omitempty"`
	WordPress     *siteWordPressArgs `json:"wordpress,omitempty"`
}

func (v *siteCreateArgs) Validate() error {
	check := &validate.V{}
	if v.Name != "" {
		if e := check.SiteName(v.Name); e != nil {
			return e
		}
	}
	if e := check.Hostname(v.PrimaryDomain); e != nil {
		return e
	}
	if (v.Type == "wordpress") != (v.WordPress != nil) {
		return rpc.Errf("invalid_argument", "WordPress settings are required only for WordPress sites")
	}
	if v.WordPress != nil {
		if err := wordpress.ValidateAdministrator(wordpress.Administrator{Title: v.WordPress.Title, Username: v.WordPress.AdminUsername, Email: v.WordPress.AdminEmail}); err != nil {
			return err
		}
	}
	if v.Type != "static" && v.Type != "php" && v.Type != "wordpress" {
		return rpc.Errf("unsupported", "Site type is not available")
	}
	if v.Type == "static" && v.PHPVersion != nil {
		return rpc.Errf("invalid_argument", "Static sites cannot select PHP")
	}
	if v.PHPVersion != nil && *v.PHPVersion != "8.3" {
		return rpc.Errf("unsupported", "Unsupported PHP version")
	}
	if v.SiteID != "" && !id.Valid(v.SiteID) {
		return rpc.Errf("invalid_argument", "Invalid site ID")
	}
	return nil
}

type siteCreateJobArgs siteCreateArgs

func (v *siteCreateJobArgs) Validate() error {
	if v.Type == "" && v.Name == "" && v.PrimaryDomain == "" && v.PHPVersion == nil && v.WordPress == nil && id.Valid(v.SiteID) {
		return nil
	}
	return (*siteCreateArgs)(v).Validate()
}

func init() {
	rpc.Register(rpc.Verb{Name: "site.create", MinRole: rpc.Admin, Scope: "sites:write", Slow: true, NewArgs: func() any { return &siteCreateArgs{} }, ObjectKey: func(args any) string { return "site:" + args.(*siteCreateArgs).Name }, NewJobArgs: func() any { return &siteCreateJobArgs{} }, JobObjectKey: func(args any) string {
		v := args.(*siteCreateJobArgs)
		if v.Type == "" {
			return "site:" + v.SiteID
		}
		return "site:" + v.Name
	}, Run: siteCreate, Exec: siteCreateExec})
}
func siteCreate(ctx context.Context, a *agent.Agent, args any) (any, error) {
	v := *args.(*siteCreateArgs)
	// Persisted identifiers are generated by the agent, never accepted from a client.
	if v.SiteID != "" {
		return nil, rpc.Errf("invalid_argument", "Site ID is agent assigned")
	}
	sid, e := id.New()
	if e != nil {
		return nil, e
	}
	if v.Name == "" {
		v.Name = "site-" + strings.ToLower(sid[:20])
	}
	if v.Type == "php" || v.Type == "wordpress" {
		if err := phpAvailable(ctx, a.Exec); err != nil {
			return nil, err
		}
		if v.PHPVersion == nil {
			version := "8.3"
			v.PHPVersion = &version
		}
	}
	v.PrimaryDomain = strings.ToLower(v.PrimaryDomain)
	did, e := id.New()
	if e != nil {
		return nil, e
	}
	var initial []store.PHPLimits
	if v.Type == "php" || v.Type == "wordpress" {
		sites, err := a.Store.ListSites(ctx)
		if err != nil {
			return nil, err
		}
		active := 0
		for _, s := range sites {
			if s.Status == "active" {
				active++
			}
		}
		cap := phpcapacity.ChildrenCap(phpcapacity.TotalMemoryMB(), active)
		initial = append(initial, store.PHPLimits{MaxChildren: &cap})
	}
	if v.Type == "wordpress" {
		evidence, ok := wpEvidence()
		if !ok {
			return nil, rpc.Errf("unsupported", "WordPress tool verification unavailable")
		}
		credentials, err := jobs.GenerateWordPressCredentials()
		if err != nil {
			return nil, err
		}
		reservation := store.WordPressReservation{SiteID: sid, DomainID: did, Input: wordpress.InstallInput{SitesRoot: a.Cfg.SitesRoot, SiteName: v.Name, PrimaryDomain: v.PrimaryDomain, Locale: wordpress.ApprovedArtifacts().Locale, Administrator: wordpress.Administrator{Title: v.WordPress.Title, Username: v.WordPress.AdminUsername, Email: v.WordPress.AdminEmail}}, Evidence: evidence}
		result, err := a.Jobs.EnqueueFreshWordPress(ctx, reservation, store.Site{ID: sid, Name: v.Name, Type: v.Type, PHPVersion: v.PHPVersion, Docroot: filepath.Join(a.Cfg.SitesRoot, v.Name, "public")}, store.Domain{ID: did, FQDN: v.PrimaryDomain}, initial[0], credentials)
		if err != nil {
			return nil, siteError(err)
		}
		return result, nil
	}
	result, e := a.Jobs.EnqueueSiteCreate(ctx, &v, "site:"+v.Name, func(ctx context.Context, tx *sql.Tx, j *jobs.Job) error {
		return a.Store.ReserveSiteTx(ctx, tx, store.Site{ID: sid, Name: v.Name, Type: v.Type, PHPVersion: v.PHPVersion, Docroot: filepath.Join(a.Cfg.SitesRoot, v.Name, "public")}, store.Domain{ID: did, FQDN: v.PrimaryDomain}, j, func(siteID string) (json.RawMessage, error) {
			v.SiteID = siteID
			return json.Marshal(&v)
		}, initial...)
	})
	if e != nil {
		return nil, siteError(e)
	}
	return result, nil
}
func siteCreateExec(ctx context.Context, a *agent.Agent, j *jobs.Job) (err error) {
	var v siteCreateArgs
	if e := json.Unmarshal(j.Args, &v); e != nil {
		return rpc.Errf("bad_request", "Invalid site arguments")
	}
	if v.Type == "" {
		return freshWordPressSiteCreateExec(ctx, a, j, v.SiteID)
	}
	if e := v.Validate(); e != nil {
		return e
	}
	if a.Jobs == nil {
		return rpc.Errf("agent_error", "Site locking unavailable")
	}
	unlock, e := a.Jobs.LockSiteCreateOSUser(ctx, v.Name)
	if e != nil {
		return e
	}
	defer unlock()
	site, e := a.Store.SiteByID(ctx, v.SiteID)
	if e != nil {
		return siteError(e)
	}
	if site.Name != v.Name || site.Type != v.Type || ((site.Type == "php" || site.Type == "wordpress") && (site.PHPVersion == nil || *site.PHPVersion != "8.3")) || site.Docroot != filepath.Join(a.Cfg.SitesRoot, v.Name, "public") || site.Status == "deleting" {
		return rpc.Errf("precondition_failed", "Site state changed")
	}
	// Active sites already completed creation; later desired state belongs to its own verbs.
	if site.Status == "active" {
		if (site.Type == "php" || site.Type == "wordpress") && j.Attempts > 1 {
			if a.PHP == nil || a.Exec == nil {
				return rpc.Errf("agent_error", "PHP execution unavailable")
			}
			if e = php.VerifyUser(ctx, a.Exec, a.Cfg.SitesRoot, site.Name, site.ID); e != nil {
				return e
			}
			limits, err := activePHPLimits(ctx, a.Store, site.ID)
			if err != nil {
				return err
			}
			cap, err := committedPHPCap(limits)
			if err != nil {
				return err
			}
			if e = a.PHP.Recover(ctx, site.Name, php.PoolState{SiteID: site.ID, Exists: true, MaxChildren: cap, Limits: limits}); e != nil {
				return e
			}
		}
		j.Result, e = json.Marshal(map[string]string{"site_id": site.ID})
		return e
	}
	poolApplied := false
	defer func() {
		if r := recover(); r != nil {
			err = rpc.Errf("agent_error", "Site creation failed")
		}
		state := "active"
		if err != nil {
			state = "failed"
		}
		cleanup, cancel := context.WithTimeout(context.WithoutCancel(ctx), 5*time.Second)
		defer cancel()
		if err != nil && poolApplied {
			err = errors.Join(err, a.PHP.Recover(cleanup, site.Name, php.PoolState{SiteID: site.ID}))
		}
		if site.Status != state {
			if statusErr := a.Store.SetSiteStatus(cleanup, site.ID, state); statusErr != nil {
				if poolApplied && state == "active" {
					statusErr = errors.Join(statusErr, a.PHP.Recover(cleanup, site.Name, php.PoolState{SiteID: site.ID}), jobs.ErrRetry)
				}
				err = errors.Join(err, statusErr)
			}
		}
	}()
	if a.ProvisionSite == nil || a.Nginx == nil {
		return rpc.Errf("agent_error", "Site execution unavailable")
	}
	if e = a.ProvisionSite(ctx, site.Name, site.ID); e != nil {
		return e
	}
	if site.Type == "php" || site.Type == "wordpress" {
		if a.PHP == nil || a.Exec == nil {
			return rpc.Errf("agent_error", "PHP execution unavailable")
		}
		if e = php.VerifyUser(ctx, a.Exec, a.Cfg.SitesRoot, site.Name, site.ID); e != nil {
			return e
		}
		if e = phpAvailable(ctx, a.Exec); e != nil {
			return e
		}
		limits, err := a.Store.SitePHPLimits(ctx, site.ID)
		if err != nil {
			return err
		}
		cap, err := committedPHPCap(limits)
		if err != nil {
			return err
		}
		committed := php.PoolState{SiteID: site.ID}
		if j.Attempts > 1 {
			if e = a.PHP.Recover(ctx, site.Name, committed); e != nil {
				return e
			}
		}
		if e = a.PHP.ApplyCommitted(ctx, site.Name, php.PoolState{SiteID: site.ID, Exists: true, MaxChildren: cap, Limits: limits}, committed); e != nil {
			return e
		}
		poolApplied = true
	}
	domains, e := a.Store.ListDomains(ctx, site.ID)
	if e != nil {
		return e
	}
	names := make([]string, 0, len(domains))
	for _, d := range domains {
		names = append(names, d.FQDN)
	}
	// Until TLS rendering is installed, never downgrade an existing certificate site.
	redirects, e := a.Store.ListRedirects(ctx, site.ID)
	if e != nil {
		return e
	}
	for _, d := range domains {
		if d.CertState != "none" {
			return rpc.Errf("precondition_failed", "Site requires TLS-aware rendering")
		}
	}
	if len(redirects) > 0 {
		return rpc.Errf("precondition_failed", "Site has redirect state; use site.update")
	}
	if site.CertSource != "none" || site.ForceHTTPS || site.Maintenance || site.HSTSMaxAge != 0 {
		return rpc.Errf("precondition_failed", "Site requires an unsupported render state")
	}
	if e = a.Nginx.Apply(ctx, nginx.Desired{Name: site.Name, Domains: names, Docroot: site.Docroot, PHPVersion: site.PHPVersion, ACMERoot: filepath.Join(a.Cfg.ACMEWebroot, site.Name)}); e != nil {
		return e
	}
	j.Result, e = json.Marshal(struct {
		SiteID string `json:"site_id"`
	}{site.ID})
	return e
}
